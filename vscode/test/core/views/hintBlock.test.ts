import { describe, expect, it } from 'vitest';
import { phpType, type PhpType } from '../../../src/core/types/phpType';
import { applyHintBlock, removeHintBlock } from '../../../src/core/views/hintBlock';

const START = '/* viewsense:start - generated by ViewSense, do not edit */';
const END = '/* viewsense:end */';

const variables = new Map<string, PhpType>([
  ['title', phpType('string', 'null')],
  ['products', phpType('Product')],
]);

describe('applyHintBlock', () => {
  it('adds a block with its own PHP tag to a view that starts with HTML', () => {
    const view = '<h1><?= $title ?></h1>\n';

    expect(applyHintBlock(view, variables)).toBe(
      [
        `<?php ${START}`,
        '/** @var Product $products */',
        '/** @var string|null $title */',
        `${END} ?>`,
        '<h1><?= $title ?></h1>',
        '',
      ].join('\n'),
    );
  });

  it('puts the block inside the first PHP tag when the view starts with one', () => {
    const view = '<?php\n\n$count = count($products);\n?>\n<p><?= $count ?></p>\n';

    expect(applyHintBlock(view, variables)).toBe(
      [
        '<?php',
        START,
        '/** @var Product $products */',
        '/** @var string|null $title */',
        END,
        '',
        '$count = count($products);',
        '?>',
        '<p><?= $count ?></p>',
        '',
      ].join('\n'),
    );
  });

  it('keeps declare(strict_types=1) as the first statement', () => {
    const view = '<?php declare(strict_types=1); ?>\n<h1><?= $title ?></h1>\n';
    const result = applyHintBlock(view, new Map([['title', phpType('string')]]));

    expect(result).toBe(
      [
        '<?php',
        START,
        '/** @var string $title */',
        END,
        'declare(strict_types=1); ?>',
        '<h1><?= $title ?></h1>',
        '',
      ].join('\n'),
    );
  });

  it('adds its own tag when the first PHP tag has code on the same line', () => {
    const view = '<?php if ($title): ?>\n<h1><?= $title ?></h1>\n<?php endif; ?>\n';
    const result = applyHintBlock(view, new Map([['title', phpType('string')]]));

    expect(result.startsWith(`<?php ${START}\n`)).toBe(true);
    expect(result.endsWith(`${END} ?>\n${view}`)).toBe(true);
  });

  it('replaces an existing block instead of adding a second one', () => {
    const once = applyHintBlock('<h1>Shop</h1>\n', variables);
    const twice = applyHintBlock(once, new Map([['title', phpType('string')]]));

    expect(twice).toBe(`<?php ${START}\n/** @var string $title */\n${END} ?>\n<h1>Shop</h1>\n`);
  });

  it.each([
    ['a view that starts with HTML', '<h1>Shop</h1>\n'],
    ['a view that starts with <?php', '<?php\n$a = 1;\n?>\n<p>Shop</p>\n'],
    ['a view with declare()', '<?php\ndeclare(strict_types=1);\n?>\n<p>Shop</p>\n'],
  ])('gives the same result when applied twice to %s', (_label, view) => {
    const once = applyHintBlock(view, variables);

    expect(applyHintBlock(once, variables)).toBe(once);
  });

  it('removes the block when the view has no variables', () => {
    const view = '<h1>Shop</h1>\n';
    const withBlock = applyHintBlock(view, variables);

    expect(applyHintBlock(withBlock, new Map())).toBe(view);
  });

  it('keeps Windows line endings', () => {
    const view = '<h1>Shop</h1>\r\n<p>Welcome</p>\r\n';
    const result = applyHintBlock(view, new Map([['title', phpType('string')]]));

    expect(result).toBe(
      `<?php ${START}\r\n/** @var string $title */\r\n${END} ?>\r\n<h1>Shop</h1>\r\n<p>Welcome</p>\r\n`,
    );
    expect(removeHintBlock(result)).toBe(view);
  });

  it('keeps the byte order mark at the start of the file', () => {
    const view = '\u{FEFF}<h1>Shop</h1>\n';
    const result = applyHintBlock(view, new Map([['title', phpType('string')]]));

    expect(result.startsWith(`\u{FEFF}<?php ${START}`)).toBe(true);
  });
});
