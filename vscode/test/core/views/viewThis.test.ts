import { describe, expect, it } from 'vitest';
import { buildClassIndex } from '../../../src/core/php/indexClasses';
import { formatType, phpType } from '../../../src/core/types/phpType';
import { applyHintBlock } from '../../../src/core/views/hintBlock';
import {
  ci3ViewProperties,
  renderCi3ViewStub,
  renderCi4ViewStub,
  usesThis,
  viewThisType,
} from '../../../src/core/views/viewThis';

describe('viewThisType', () => {
  it('is a generated class for each version, written fully qualified', () => {
    expect(formatType(viewThisType(4))).toBe('\\ViewSense_CI4_View');
    expect(formatType(viewThisType(3))).toBe('\\ViewSense_CI3_View');
  });
});

describe('renderCi4ViewStub', () => {
  it('extends the view renderer and lets extend(), section() and endSection() be printed', () => {
    const stub = renderCi4ViewStub();

    expect(stub).toContain('class ViewSense_CI4_View extends \\CodeIgniter\\View\\View');
    expect(stub).toContain(' * @method null extend(string $layout)\n');
    expect(stub).toContain(' * @method null section(string $name)\n');
    expect(stub).toContain(' * @method null endSection()\n');
  });
});

describe('usesThis', () => {
  it.each([
    ['<?= $this->extend("layout") ?>', true],
    ['<?php $this->load->view("x"); ?>', true],
    ['<?= $thisProduct ?>', false],
    ['<p>Nothing here</p>', false],
  ])('%s gives %s', (code, expected) => {
    expect(usesThis(code)).toBe(expected);
  });
});

describe('ci3ViewProperties', () => {
  it('merges core classes, loaded classes and controller properties', () => {
    const classes = buildClassIndex([
      {
        path: 'MY_Controller.php',
        code: `<?php
          /** @property Cart $cart */
          class MY_Controller extends CI_Controller {
            public function __construct() { $this->load->library('session'); }
          }`,
      },
      {
        path: 'Shop.php',
        code: `<?php
          class Shop extends MY_Controller {
            public ?string $title = null;
            /** @var Basket */
            public $cart;
          }`,
      },
      {
        path: 'Other.php',
        code: '<?php class Product_model extends CI_Model { public int $notInViews = 0; }',
      },
    ]);

    const properties = ci3ViewProperties(classes);
    const typeOf = (name: string): string | undefined => {
      const type = properties.get(name);
      return type === undefined ? undefined : formatType(type);
    };

    expect(typeOf('load')).toBe('\\CI_Loader');
    expect(typeOf('input')).toBe('\\CI_Input');
    expect(typeOf('session')).toBe('\\Session');
    expect(typeOf('title')).toBe('string|null');
    // A view can't know which controller renders it: MY_Controller says Cart, Shop says Basket.
    expect(typeOf('cart')).toBe('\\Basket|\\Cart');
    expect(typeOf('notInViews')).toBeUndefined();
  });
});

describe('renderCi3ViewStub', () => {
  it('writes a class with one @property line per property, sorted by name', () => {
    const stub = renderCi3ViewStub(
      new Map([
        ['session', phpType('\\CI_Session')],
        ['cart', phpType('\\Cart', 'null')],
      ]),
    );

    expect(stub).toBe(
      [
        '<?php',
        '',
        '// Generated by ViewSense for CodeIgniter. Do not edit: each update rewrites this file.',
        '',
        '/**',
        ' * `$this` in a CodeIgniter 3 view: the loader, plus what the controllers can reach.',
        ' *',
        ' * @property \\Cart|null $cart',
        ' * @property \\CI_Session $session',
        ' */',
        'class ViewSense_CI3_View extends \\CI_Loader',
        '{',
        '}',
        '',
      ].join('\n'),
    );
  });
});

describe('hint block with $this', () => {
  it('puts $this before the other variables', () => {
    const block = applyHintBlock(
      '<p>Shop</p>\n',
      new Map([
        ['title', phpType('string')],
        ['this', phpType('\\CodeIgniter\\View\\View')],
        ['alpha', phpType('int')],
      ]),
    );

    expect(block.split('\n').slice(1, 4)).toEqual([
      '/** @var \\CodeIgniter\\View\\View $this */',
      '/** @var int $alpha */',
      '/** @var string $title */',
    ]);
  });
});
