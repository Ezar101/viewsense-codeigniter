import type { ClassIndex } from '../php/classIndex';
import type { CodeIgniterVersion } from '../project/detectProject';
import { formatType, phpType, unionTypes, type PhpType } from '../types/phpType';

/**
 * In a CodeIgniter 4 view, `$this` is the view renderer.
 * In a CodeIgniter 3 view, `$this` is the loader (`CI_Loader`), which also gives access to
 * everything the controller can reach (`$this->session`, `$this->cart`...). No real class
 * describes that, so ViewSense generates one: `ViewSense_CI3_View`.
 */
const CI4_VIEW_TYPE = phpType('\\CodeIgniter\\View\\View');
const CI3_VIEW_CLASS = 'ViewSense_CI3_View';

/** Folder for the files ViewSense generates, relative to the project root. */
export const GENERATED_FOLDER = '.viewsense';
export const CI3_STUB_PATH = `${GENERATED_FOLDER}/ci3_view.php`;
/** Makes Git ignore the generated folder without touching the project's own `.gitignore`. */
export const GENERATED_GITIGNORE_PATH = `${GENERATED_FOLDER}/.gitignore`;

/** Classes CodeIgniter 3 always loads into its instance, by property name. */
const CI3_CORE_PROPERTIES: readonly [string, string][] = [
  ['benchmark', 'CI_Benchmark'],
  ['config', 'CI_Config'],
  ['hooks', 'CI_Hooks'],
  ['input', 'CI_Input'],
  ['lang', 'CI_Lang'],
  ['load', 'CI_Loader'],
  ['log', 'CI_Log'],
  ['output', 'CI_Output'],
  ['router', 'CI_Router'],
  ['security', 'CI_Security'],
  ['uri', 'CI_URI'],
  ['utf8', 'CI_Utf8'],
];

export function viewThisType(version: CodeIgniterVersion): PhpType {
  return version === 4 ? CI4_VIEW_TYPE : phpType(CI3_VIEW_CLASS);
}

/** True when a view refers to `$this`, e.g. `$this->extend()` or `$this->session`. */
export function usesThis(code: string): boolean {
  return /\$this\b/.test(code);
}

/**
 * Properties of `$this` in a CodeIgniter 3 view: the core classes, everything the loader loaded,
 * and the properties of every controller. A property with different types gets their union.
 */
export function ci3ViewProperties(classes: ClassIndex): Map<string, PhpType> {
  const properties = new Map<string, PhpType>();
  const add = (name: string, type: PhpType): void => {
    const known = properties.get(name);
    properties.set(name, known === undefined ? type : unionTypes(known, type));
  };

  for (const [name, className] of CI3_CORE_PROPERTIES) {
    add(name, phpType(className));
  }
  for (const [name, type] of classes.loadedProperties) {
    add(name, type);
  }
  for (const controller of classes.subclassesOf('CI_Controller')) {
    for (const [name, type] of classes.allProperties(controller.name)) {
      add(name, type);
    }
  }
  return properties;
}

/** Source of the generated `ViewSense_CI3_View` class. */
export function renderCi3ViewStub(properties: ReadonlyMap<string, PhpType>): string {
  const propertyLines = [...properties]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([name, type]) => ` * @property ${formatType(type)} $${name}`);

  return [
    '<?php',
    '',
    '// Generated by ViewSense for CodeIgniter. Do not edit: each update rewrites this file.',
    '',
    '/**',
    ' * `$this` in a CodeIgniter 3 view: the loader, plus what the controllers can reach.',
    ' *',
    ...propertyLines,
    ' */',
    `class ${CI3_VIEW_CLASS} extends CI_Loader`,
    '{',
    '}',
    '',
  ].join('\n');
}
